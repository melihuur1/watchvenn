export const CATALOG: readonly CatalogMovie[] = ENTRIES.map((entry) => ({ kind: 'catalog', ...entry }));

const CATALOG_BY_ID = new Map(CATALOG.map((movie) => [movie.id, movie]));

export function findCatalogMovie(id: string): CatalogMovie | undefined {
  return CATALOG_BY_ID.get(id);
}

/** Gradients for custom titles. Dark enough that white text stays readable on every one. */
export const CUSTOM_PALETTES: readonly Palette[] = [
  ['#7c2d12', '#be123c'],
  ['#1e3a8a', '#6d28d9'],
  ['#134e4a', '#0369a1'],
  ['#4c1d95', '#be185d'],
  ['#365314', '#0f766e'],
  ['#78350f', '#b91c1c'],
  ['#1f2937', '#4338ca'],
  ['#831843', '#c2410c'],
];

/** The same title (ignoring case, Turkish rules) always gets the same gradient (FNV-1a hash). */
export function paletteForTitle(title: string): Palette {
  let hash = 0x811c9dc5;
  for (const char of foldKey(title)) {
    hash ^= char.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 0x01000193);
  }
  return CUSTOM_PALETTES[(hash >>> 0) % CUSTOM_PALETTES.length]!;
}

/** Builds the movie stored for a free-text candidate. The id must be unique within the room. */
export function customMovie(id: string, title: string): CustomMovie {
  return { kind: 'custom', id, title, palette: paletteForTitle(title) };
}
